// Delete Link
function deleteLink(id, callback) {
    getLinks((links) => {
        const filteredLinks = links.filter(link => link.id !== id);
        saveLinks(filteredLinks, callback);
    });
}

// Update Link
function updateLink(id, updates, callback) {
    getLinks((links) => {
        const updatedLinks = links.map(link => 
            link.id === id ? { ...link, ...updates } : link
        );
        saveLinks(updatedLinks, callback);
    });
}

// Get Categories from Links with saved order
function getCategories(links) {
    return new Promise((resolve) => {
        // Ensure links is an array
        if (!Array.isArray(links)) {
            resolve([]);
            return;
        }
        
        storage.get(['categoryOrder'], (result) => {
            const savedOrder = result.categoryOrder || [];
            const categories = new Set();
            links.forEach(link => {
                if (link && link.category) {
                    categories.add(link.category);
                }
            });
            
            // Use saved order if available, otherwise sort alphabetically
            const orderedCategories = [];
            if (savedOrder.length > 0) {
                // Add categories in saved order
                savedOrder.forEach(cat => {
                    if (categories.has(cat)) {
                        orderedCategories.push(cat);
                        categories.delete(cat);
                    }
                });
                // Add any new categories that weren't in saved order
                const remainingCategories = Array.from(categories).sort();
                orderedCategories.push(...remainingCategories);
            } else {
                // No saved order, use alphabetical
                orderedCategories.push(...Array.from(categories).sort());
            }
            
            // Always return an array
            resolve(Array.isArray(orderedCategories) ? orderedCategories : []);
        });
    });
}

// Load Data
function loadData() {
    loadSearchEngine();
    updateSearchEngineButtons(); // Load custom search engines
    
    // Load saved category and order first
    storage.get(['lastCategory', 'categoryOrder'], (result) => {
        // Restore last selected category
        if (result.lastCategory) {
            currentCategory = result.lastCategory;
        }
        
        getLinks((links) => {
            getCategories(links).then((categories) => {
                // Always set a default category if none is set or current doesn't exist
                if (categories.length > 0) {
                    if (!currentCategory || !categories.includes(currentCategory)) {
                        currentCategory = categories[0];
                    }
                    // Always save the selected category (even if it was restored)
                    storage.set({ lastCategory: currentCategory });
                }
                
                renderCategories(categories);
                renderLinks(links);
            });
        });
    });
}

// Render Categories
function renderCategories(categories) {
    categoriesTabs.innerHTML = '';
    
    if (categories.length === 0) {
        return;
    }
    
    categories.forEach(categoryName => {
        const tab = document.createElement('button');
        tab.className = `category-tab ${categoryName === currentCategory ? 'active' : ''}`;
        tab.textContent = categoryName;
        tab.dataset.category = categoryName;
        tab.draggable = true; // Make category tabs draggable for reordering
        
        // Edit button
        const editBtn = document.createElement('span');
        editBtn.className = 'edit-category';
        editBtn.setAttribute('role', 'button');
        editBtn.innerHTML = '<svg width="11" height="11" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.5" stroke-linecap="round" stroke-linejoin="round"><path d="M16.5 3.5a2.1 2.1 0 0 1 3 3L7 19l-4 1 1-4Z"/></svg>';
        editBtn.title = t('editCategory');
        editBtn.addEventListener('click', (e) => {
            e.stopPropagation();
            editCategory(categoryName);
        });
        
        // Delete button
        const deleteBtn = document.createElement('span');
        deleteBtn.className = 'delete-category';
        deleteBtn.setAttribute('role', 'button');
        deleteBtn.innerHTML = '<svg width="11" height="11" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.5" stroke-linecap="round"><path d="M18 6 6 18M6 6l12 12"/></svg>';
        deleteBtn.title = t('deleteCategory');
        deleteBtn.addEventListener('click', (e) => {
            e.stopPropagation();
            deleteCategory(categoryName);
        });
        
        tab.appendChild(editBtn);
        tab.appendChild(deleteBtn);
        
        tab.addEventListener('click', () => {
            switchCategory(categoryName);
        });
        
        // Drag and drop handlers for category tabs (reordering categories)
        tab.addEventListener('dragstart', (e) => {
            draggedCategoryElement = tab;
            tab.style.opacity = '0.5';
            e.dataTransfer.effectAllowed = 'move';
        });
        
        tab.addEventListener('dragend', (e) => {
            tab.style.opacity = '1';
            
            // Save order when drag ends (in case drop didn't fire properly)
            if (draggedCategoryElement) {
                setTimeout(() => {
                    const newOrder = Array.from(categoriesTabs.children)
                        .map(child => child.dataset.category)
                        .filter(cat => cat && cat !== undefined);
                    
                    if (newOrder.length > 0) {
                        saveCategoryOrder(newOrder);
                    }
                }, 100);
            }
            
            draggedCategoryElement = null;
            // Remove drag-over class from all tabs
            document.querySelectorAll('.category-tab').forEach(t => {
                t.classList.remove('drag-over-category');
            });
        });
        
        // Make category tab a drop target for links AND for reordering categories
        tab.addEventListener('dragover', (e) => {
            e.preventDefault();
            e.stopPropagation();
            
            // Handle category reordering
            if (draggedCategoryElement && draggedCategoryElement !== tab) {
                e.dataTransfer.dropEffect = 'move';
                const rect = tab.getBoundingClientRect();
                const mid = rect.left + rect.width / 2;
                if (e.clientX < mid) {
                    categoriesTabs.insertBefore(draggedCategoryElement, tab);
                } else {
                    categoriesTabs.insertBefore(draggedCategoryElement, tab.nextSibling);
                }
            }
            
            // Handle link being dragged over category tab
            if (draggedElement && draggedElement.classList.contains('link-item')) {
                e.dataTransfer.dropEffect = 'move';
                tab.classList.add('drag-over-category');
            }
        });
        
        tab.addEventListener('dragleave', (e) => {
            // Only remove highlight if we're actually leaving the tab
            if (!tab.contains(e.relatedTarget)) {
                tab.classList.remove('drag-over-category');
            }
        });
        
        tab.addEventListener('drop', (e) => {
            e.preventDefault();
            e.stopPropagation();
            
            // Handle category reordering
            if (draggedCategoryElement && draggedCategoryElement !== tab) {
                // Get new order from DOM
                const newOrder = Array.from(categoriesTabs.children)
                    .map(child => child.dataset.category)
                    .filter(cat => cat); // Filter out any null/undefined values
                
                // Save new order immediately
                if (newOrder.length > 0) {
                    saveCategoryOrder(newOrder);
                }
            }
            
            // Handle link being dropped on category tab
            if (draggedElement && draggedElement.classList.contains('link-item')) {
                const linkId = parseInt(draggedElement.dataset.id);
                getLinks((links) => {
                    const updatedLinks = links.map(link => {
                        if (link.id === linkId) {
                            return { ...link, category: categoryName };
                        }
                        return link;
                    });
                    
                    saveLinks(updatedLinks, () => {
                        // Switch to the new category if not already there
                        if (currentCategory !== categoryName) {
                            currentCategory = categoryName;
                        }
                        getLinks((allLinks) => {
                            getCategories(allLinks).then((categories) => {
                                renderCategories(categories);
                                renderLinks(allLinks);
                            });
                        });
                    });
                });
            }
            
            tab.classList.remove('drag-over-category');
        });
        
        categoriesTabs.appendChild(tab);
    });
}

