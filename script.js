// Handle Search Engine Submit with duplicate protection
function handleSearchEngineSubmit(e) {
    e.preventDefault();
    
    const name = document.getElementById('search-engine-name').value.trim();
    const url = document.getElementById('search-engine-url').value.trim();
    const imageUrl = document.getElementById('search-engine-image-url').value.trim();
    const iconField = document.getElementById('search-engine-icon');
    const icon = iconField ? iconField.value : '';
    
    if (!name || !url) {
        alert(t('importError') + ': ' + t('enterCategoryName'));
        return;
    }
    
    // Check if URL contains {query} placeholder
    if (!url.includes('{query}')) {
        alert(t('importError') + ': ' + 'URL должен содержать {query}');
        return;
    }
    
    storage.get(['customSearchEngines'], (result) => {
        const customEngines = result.customSearchEngines || {};
        
        // Проверка на дубли по названию
        const nameLower = name.toLowerCase();
        const existingByName = Object.values(customEngines).find(engine => 
            engine.name.toLowerCase() === nameLower
        );
        if (existingByName && !editingSearchEngineId) {
            alert(t('importError') + ': ' + 'Поисковая система с таким названием уже существует');
            return;
        }
        
        // Проверка на дубли по URL (нормализованный)
        const urlNormalized = url.toLowerCase().replace(/\s+/g, '');
        const existingByUrl = Object.entries(customEngines).find(([id, engine]) => {
            if (editingSearchEngineId && id === editingSearchEngineId) return false;
            const engineUrlNormalized = engine.url.toLowerCase().replace(/\s+/g, '');
            return engineUrlNormalized === urlNormalized;
        });
        if (existingByUrl) {
            alert(t('importError') + ': ' + 'Поисковая система с таким URL уже существует');
            return;
        }
        
        if (editingSearchEngineId) {
            // Update existing
            customEngines[editingSearchEngineId] = {
                name: name,
                url: url,
                imageUrl: imageUrl || '',
                icon: icon || ''
            };
        } else {
            // Add new - generate unique ID
            const engineId = 'custom_' + Date.now();
            customEngines[engineId] = {
                name: name,
                url: url,
                imageUrl: imageUrl || '',
                icon: icon || ''
            };
        }
        
        storage.set({ customSearchEngines: customEngines }, () => {
            updateSearchEngineButtons();
            closeModals();
        });
    });
}

