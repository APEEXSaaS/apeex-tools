// Handle Link Submit with duplicate protection and click prevention
function handleLinkSubmit(e) {
    e.preventDefault();
    
    const submitButton = document.getElementById('submit-btn');
    
    // Prevent multiple clicks - disable button
    if (submitButton.disabled) {
        return; // Already processing
    }
    
    const name = document.getElementById('link-name').value.trim();
    const url = document.getElementById('link-url').value.trim();
    const category = document.getElementById('link-category').value;
    const icon = getLinkIconField();
    
    if (!name || !url || !category) {
        return;
    }
    
    // Ensure URL has protocol - automatically add https:// if missing
    let fullUrl = url.trim();
    if (!fullUrl.startsWith('http://') && !fullUrl.startsWith('https://')) {
        // Remove any leading slashes and add https://
        fullUrl = fullUrl.replace(/^\/+/, '');
        fullUrl = 'https://' + fullUrl;
    }
    
    // Normalize URL for comparison (remove trailing slash, convert to lowercase)
    const normalizedUrl = fullUrl.toLowerCase().replace(/\/+$/, '');
    
    if (editingLinkId !== null) {
        // Update existing link
        // Disable button during save
        submitButton.disabled = true;
        submitButton.textContent = t('save') + '...';
        
        // Check for duplicates when editing (excluding current link)
        getLinks((allLinks) => {
            const normalizedUrl = fullUrl.toLowerCase().replace(/\/+$/, '');
            
            // Check for duplicates by URL (excluding current link)
            const duplicateByUrl = allLinks.find(link => {
                if (link.id === editingLinkId) return false; // Skip current link
                const linkUrl = link.url.toLowerCase().replace(/\/+$/, '');
                return linkUrl === normalizedUrl;
            });
            
            if (duplicateByUrl) {
                alert(t('importError') + ': ' + 'Ссылка с таким URL уже существует: ' + duplicateByUrl.name);
                submitButton.disabled = false;
                submitButton.textContent = t('save');
                return;
            }
            
            // Check for duplicates by name in the same category (excluding current link)
            const duplicateByName = allLinks.find(link => {
                if (link.id === editingLinkId) return false; // Skip current link
                return link.category === category && 
                       link.name.toLowerCase() === name.toLowerCase();
            });
            
            if (duplicateByName) {
                alert(t('importError') + ': ' + 'Ссылка с таким названием уже существует в этой категории: ' + duplicateByName.name);
                submitButton.disabled = false;
                submitButton.textContent = t('save');
                return;
            }
            
            updateLink(editingLinkId, {
                name,
                url: fullUrl,
                category,
                icon: icon || undefined
            }, () => {
                getLinks((links) => {
                    getCategories(links).then((categories) => {
                        renderCategories(categories);
                        
                        // Switch to link's category if different
                        if (category !== currentCategory) {
                            currentCategory = category;
                        }
                        
                        renderLinks(links);
                        closeModals();
                        
                        // Re-enable button
                        submitButton.disabled = false;
                        submitButton.textContent = t('save');
                    });
                });
            });
        });
    } else {
        // Add new link - check for duplicates first
        getLinks((links) => {
            // Check for duplicates by URL (normalized)
            const duplicateByUrl = links.find(link => {
                if (link.id === editingLinkId) return false; // Skip current link if editing
                const linkUrl = link.url.toLowerCase().replace(/\/+$/, '');
                return linkUrl === normalizedUrl;
            });
            
            if (duplicateByUrl) {
                alert(t('importError') + ': ' + 'Ссылка с таким URL уже существует: ' + duplicateByUrl.name);
                submitButton.disabled = false;
                submitButton.textContent = t('add');
                return;
            }
            
            // Check for duplicates by name in the same category (case-insensitive)
            const duplicateByName = links.find(link => {
                if (link.id === editingLinkId) return false; // Skip current link if editing
                return link.category === category && 
                       link.name.toLowerCase() === name.toLowerCase();
            });
            
            if (duplicateByName) {
                alert(t('importError') + ': ' + 'Ссылка с таким названием уже существует в этой категории: ' + duplicateByName.name);
                submitButton.disabled = false;
                submitButton.textContent = t('add');
                return;
            }
            
            // Disable button during save
            submitButton.disabled = true;
            submitButton.textContent = t('add') + '...';
            
            addLink(name, fullUrl, category, () => {
                getLinks((links) => {
                    getCategories(links).then((categories) => {
                        renderCategories(categories);
                        
                        // Switch to link's category if different
                        if (category !== currentCategory) {
                            currentCategory = category;
                        }
                        
                        renderLinks(links);
                        closeModals();
                        
                        // Re-enable button
                        submitButton.disabled = false;
                        submitButton.textContent = t('add');
                    });
                });
            }, icon);
        });
    }
}

// Handle Category Submit
function handleCategorySubmit(e) {
    e.preventDefault();
    
    const name = document.getElementById('category-name').value.trim();
    
    if (!name) {
        alert(t('enterCategoryName'));
        return;
    }
    
    getLinks((links) => {
        getCategories(links).then((categories) => {
            // Check if editing or adding
            if (editingCategoryName) {
                // Editing existing category
                if (name !== editingCategoryName && categories.includes(name)) {
                    alert(t('categoryExists'));
                    return;
                }
                
                // Update all links with old category name to new category name
                const updatedLinks = links.map(link => {
                    if (link.category === editingCategoryName) {
                        return { ...link, category: name };
                    }
                    return link;
                });
                
                // Update category order if category was renamed
                storage.get(['categoryOrder'], (result) => {
                    const savedOrder = result.categoryOrder || [];
                    const updatedOrder = savedOrder.map(cat => 
                        cat === editingCategoryName ? name : cat
                    );
                    
                    saveLinks(updatedLinks, () => {
                        if (updatedOrder.length > 0) {
                            storage.set({ categoryOrder: updatedOrder }, () => {
                                getLinks((allLinks) => {
                                    getCategories(allLinks).then((updatedCategories) => {
                                        if (currentCategory === editingCategoryName) {
                                            currentCategory = name;
                                        }
                                        renderCategories(updatedCategories);
                                        renderLinks(allLinks);
                                        closeModals();
                                    });
                                });
                            });
                        } else {
                            getLinks((allLinks) => {
                                getCategories(allLinks).then((updatedCategories) => {
                                    if (currentCategory === editingCategoryName) {
                                        currentCategory = name;
                                    }
                                    renderCategories(updatedCategories);
                                    renderLinks(allLinks);
                                    closeModals();
                                });
                            });
                        }
                    });
                });
            } else {
                // Adding new category
                if (categories.includes(name)) {
                    alert(t('categoryExists'));
                    return;
                }
                
                // Create a placeholder link to establish the category
                const placeholderLink = {
                    id: Date.now(),
                    name: '_placeholder_',
                    url: 'https://placeholder.local',
                    category: name
                };
                
                links.push(placeholderLink);
                saveLinks(links, () => {
                    getLinks((updatedLinks) => {
                        // Filter out placeholder links when rendering
                        const displayLinks = updatedLinks.filter(link => link.name !== '_placeholder_');
                        getCategories(updatedLinks).then((updatedCategories) => {
                            // Add new category to order
                            storage.get(['categoryOrder'], (result) => {
                                const savedOrder = result.categoryOrder || [];
                                savedOrder.push(name);
                                storage.set({ categoryOrder: savedOrder }, () => {
                                    currentCategory = name;
                                    renderCategories(updatedCategories);
                                    renderLinks(displayLinks);
                                    closeModals();
                                });
                            });
                        });
                    });
                });
            }
        });
    });
}

