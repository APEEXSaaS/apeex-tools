// Perform Search
function performSearch() {
    const query = searchInput.value.trim();
    if (!query) {
        // Don't search with empty query
        return;
    }
    
    getAllSearchEngines((allEngines) => {
        const engine = allEngines[currentSearchEngine];
        if (!engine || !engine.url) {
            return;
        }
        
        // Replace {query} placeholder with actual query
        let searchUrl = engine.url;
        if (searchUrl.includes('{query}')) {
            searchUrl = searchUrl.replace('{query}', encodeURIComponent(query));
        } else {
            // Fallback: if no {query} placeholder, append query to URL
            searchUrl = searchUrl + encodeURIComponent(query);
        }
        
        // Open in the same tab instead of new tab
        window.location.href = searchUrl;
    });
}

// Handle Image Search
function handleImageSearch(e) {
    const file = e.target.files[0];
    if (!file) return;

    // Convert image to base64 or data URL
    const reader = new FileReader();
    reader.onload = function(event) {
        const imageDataUrl = event.target.result;
        performImageSearch(imageDataUrl);
    };
    reader.readAsDataURL(file);
    
    // Reset input
    e.target.value = '';
}

// Perform Image Search
function performImageSearch(imageDataUrl) {
    getAllSearchEngines((allEngines) => {
        const engine = allEngines[currentSearchEngine];
        if (!engine) return;
        
        // For Google Lens - use direct upload
        if (currentSearchEngine === 'google') {
            // Google Lens requires uploading the image
            window.location.href = 'https://lens.google.com/';
            // Note: Google Lens doesn't support direct URL upload from data URL
            // User will need to upload manually
            return;
        }
        
        // Check if custom engine has imageUrl
        if (engine.imageUrl) {
            // Use custom image search URL
            fetch(imageDataUrl)
                .then(res => res.blob())
                .then(blob => {
                    const imageUrl = URL.createObjectURL(blob);
                    const searchUrl = engine.imageUrl.replace('{query}', imageUrl);
                    window.location.href = searchUrl;
                    setTimeout(() => URL.revokeObjectURL(imageUrl), 1000);
                })
                .catch(() => {
                    // Fallback to regular image search
                    window.location.href = engine.imageUrl.replace('{query}', '');
                });
            return;
        }
        
        // For other engines, try to use image URL
        // Convert data URL to blob and upload
        fetch(imageDataUrl)
            .then(res => res.blob())
            .then(blob => {
                // Create a temporary URL for the image
                const imageUrl = URL.createObjectURL(blob);
                
                if (currentSearchEngine === 'yandex') {
                    // Yandex image search
                    window.location.href = 'https://yandex.ru/images/search?source=collections';
                } else if (currentSearchEngine === 'bing') {
                    // Bing visual search
                    window.location.href = 'https://www.bing.com/visualsearch';
                } else {
                    // DuckDuckGo - redirect to image search
                    window.location.href = 'https://duckduckgo.com/?iax=images&ia=images';
                }
                
                // Clean up
                setTimeout(() => URL.revokeObjectURL(imageUrl), 1000);
            })
            .catch(() => {
                // Fallback: open image search page
                if (currentSearchEngine === 'yandex') {
                    window.location.href = 'https://yandex.ru/images/';
                } else if (currentSearchEngine === 'bing') {
                    window.location.href = 'https://www.bing.com/images/';
                } else {
                    window.location.href = 'https://duckduckgo.com/?iax=images&ia=images';
                }
            });
    });
}

